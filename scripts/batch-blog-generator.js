function loadState() {
  if (fs.existsSync(STATE_FILE)) {
    return JSON.parse(fs.readFileSync(STATE_FILE, 'utf8'));
  }
  return {
    bartact: { lastPublished: null, publishedCount: 0, queue: [...BLOG_TOPICS.bartact] },
    bullstrap: { lastPublished: null, publishedCount: 0, queue: [...BLOG_TOPICS.bullstrap] }
  };
}

function saveState(state) {
  fs.writeFileSync(STATE_FILE, JSON.stringify(state, null, 2));
}

