function indexUrl(url) {
  // Submit to Google Indexing API
  try {
    execSync(`node ${WORKSPACE}/scripts/bartact-publish-and-index.js --url "${url}"`, { stdio: 'inherit' });
    return true;
  } catch (e) {
    console.error(`Failed to index ${url}:`, e.message);
    return false;
  }
}

async function main() {
  const args = process.argv.slice(2);
  const site = args.find(a => a === 'bartact' || a === 'bullstrap') || 'both';
  const count = parseInt(args.find(a => a.startsWith('--count='))?.split('=')[1]) || 1;
  
  console.log(`📝 Blog Post Generator — ${site} (${count} post${count > 1 ? 's' : ''})`);
  
  const state = loadState();
  const results = [];
  
  const sites = site === 'both' ? ['bartact', 'bullstrap'] : [site];
  
  for (const currentSite of sites) {
    const siteState = state[currentSite];
    
    if (siteState.queue.length === 0) {
      console.log(`⚠️  ${currentSite}: No topics left in queue`);
      continue;
    }
    
    for (let i = 0; i < count && siteState.queue.length > 0; i++) {
      const topic = siteState.queue.shift();
      
      try {
        console.log(`\n📄 Generating: ${topic.title}`);
        const post = generateBlogPost(currentSite, topic);
        
        console.log(`📤 Publishing to ${currentSite} Shopify...`);
        const publishResult = publishToShopify(currentSite, post);
        
        if (publishResult.success) {
          console.log(`✅ Published: ${publishResult.url}`);
          
          console.log(`🔍 Submitting to Google Indexing API...`);
          const indexed = indexUrl(publishResult.url);
          
          results.push({
            site: currentSite,
            title: topic.title,
            url: publishResult.url,
            indexed: indexed,
            publishedAt: new Date().toISOString()
          });
          
          siteState.lastPublished = new Date().toISOString();
          siteState.publishedCount++;
        }
      } catch (error) {
        console.error(`❌ Failed to publish "${topic.title}":`, error.message);
        // Put topic back at end of queue on failure
        siteState.queue.push(topic);
      }
    }
  }
  
  saveState(state);
  
  // Generate report
  const now = new Date();
  let report = `# 📊 Blog Posts — ${now.toISOString().split('T')[0]}\n\n`;
  report += `**Run Date:** ${now.toUTCString()}\n\n`;
  
  if (results.length === 0) {
    report += `## Status: ⚠️ NO POSTS PUBLISHED\n\n`;
    report += `No blog posts were generated in this run.\n`;
  } else {
    report += `## Status: ✅ ${results.length} POST${results.length > 1 ? 'S' : ''} PUBLISHED\n\n`;
    
    for (const result of results) {
      const indexStatus = result.indexed ? '✅ Indexed' : '⚠️ Index failed';
      report += `### ${result.site.charAt(0).toUpperCase() + result.site.slice(1)}: ${result.title}\n`;
      report += `- **URL:** ${result.url}\n`;
      report += `- **Status:** ${indexStatus}\n`;
      report += `- **Published:** ${result.publishedAt}\n\n`;
    }
  }
  
  report += `### Queue Status\n`;
  for (const siteName of ['bartact', 'bullstrap']) {
    const s = state[siteName];
    report += `- **${siteName}:** ${s.queue.length} topics remaining, ${s.publishedCount} total published\n`;
  }
  
  fs.writeFileSync(OUTPUT_FILE, report);
  console.log(`\n✅ Report saved to ${OUTPUT_FILE}`);
  console.log('\n' + report);
}

if (require.main === module) {
  main().catch(err => {
    console.error('❌ Fatal error:', err);
    process.exit(1);
  });
}

module.exports = { generateBlogPost, publishToShopify, loadState, saveState };
